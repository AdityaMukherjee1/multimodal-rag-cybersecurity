"""Robust parser and validator for structured LLM investigation outputs.

Handles JSON markdown wrapping, trailing commas, partial outputs,
and gracefully falls back to regex-assisted claim and citation extraction.
"""

from __future__ import annotations

import json
import logging
import re
from typing import Any

from src.llm.schema import Claim, StructuredInvestigationAnswer

logger = logging.getLogger(__name__)

# Pattern to locate JSON object within markdown code blocks or free text
JSON_BLOCK_PATTERN = re.compile(r"```(?:json)?\s*(\{.*?\})\s*```", re.DOTALL)
CITED_EVIDENCE_PATTERN = re.compile(r"\[([A-Za-z0-9_\-\.\:\/]+)\]")
ATTCK_PATTERN = re.compile(r"\b(T\d{4}(?:\.\d{3})?)\b", re.IGNORECASE)
CVE_PATTERN = re.compile(r"\b(CVE-\d{4}-\d{4,7})\b", re.IGNORECASE)


class InvestigationOutputParser:
    """Parses and validates LLM generation into StructuredInvestigationAnswer."""

    @classmethod
    def parse(
        cls,
        raw_text: str,
        model_name: str = "",
        token_usage: dict[str, int] | None = None,
    ) -> StructuredInvestigationAnswer:
        """Parse raw model text into a validated StructuredInvestigationAnswer.

        Args:
            raw_text: Text output returned by the LLM.
            model_name: Name of model that produced the output.
            token_usage: Token counts dictionary (if reported by provider).

        Returns:
            StructuredInvestigationAnswer instance.
        """
        if not raw_text or not raw_text.strip():
            logger.warning("Empty LLM response received in parser.")
            return StructuredInvestigationAnswer(
                answer="No response generated by the language model.",
                confidence="low",
                limitations=["LLM returned an empty response."],
                raw_response=raw_text,
                is_parsed_json=False,
                model_name=model_name,
                token_usage=token_usage or {},
            )

        cleaned_text = raw_text.strip()

        # 1. Attempt extracting JSON from markdown code block
        json_str = cls._extract_json_substring(cleaned_text)

        # 2. Try parsing JSON
        data: dict[str, Any] | None = None
        is_clean_json = False
        try:
            data = json.loads(json_str)
            if isinstance(data, dict):
                is_clean_json = True
        except json.JSONDecodeError as exc:
            logger.warning("Direct JSON decode failed: %s. Attempting sanitized parse.", exc)
            data = cls._attempt_sanitized_json(json_str)
            if data is not None:
                is_clean_json = True

        # 3. If valid dict obtained, build StructuredInvestigationAnswer
        if is_clean_json and data is not None:
            return cls._build_from_dict(
                data=data,
                raw_text=cleaned_text,
                model_name=model_name,
                token_usage=token_usage or {},
            )

        # 4. Fallback: Parse non-JSON / malformed output using heuristics & regex
        logger.warning("Structured JSON parsing failed. Engaging heuristic fallback parser.")
        return cls._fallback_parse(
            raw_text=cleaned_text,
            model_name=model_name,
            token_usage=token_usage or {},
        )

    @classmethod
    def _extract_json_substring(cls, text: str) -> str:
        """Extract JSON substring, unwrapping markdown if present."""
        match = JSON_BLOCK_PATTERN.search(text)
        if match:
            return match.group(1).strip()

        # If wrapped in bare braces
        start = text.find("{")
        end = text.rfind("}")
        if start != -1 and end != -1 and end > start:
            return text[start : end + 1].strip()

        return text

    @classmethod
    def _attempt_sanitized_json(cls, text: str) -> dict[str, Any] | None:
        """Try fixing common JSON errors like trailing commas."""
        sanitized = re.sub(r",\s*([\]}])", r"\1", text)
        try:
            res = json.loads(sanitized)
            if isinstance(res, dict):
                return res
        except Exception:
            pass
        return None

    @classmethod
    def _build_from_dict(
        cls,
        data: dict[str, Any],
        raw_text: str,
        model_name: str,
        token_usage: dict[str, int],
    ) -> StructuredInvestigationAnswer:
        """Construct verified StructuredInvestigationAnswer from parsed dictionary."""
        answer = str(data.get("answer", "")).strip()
        confidence = str(data.get("confidence", "preliminary")).strip()

        # Parse claims
        claims: list[Claim] = []
        raw_claims = data.get("claims", [])
        if isinstance(raw_claims, list):
            for i, c in enumerate(raw_claims, start=1):
                if isinstance(c, dict):
                    c_id = str(c.get("claim_id") or f"CLAIM-{i:03d}")
                    c_text = str(c.get("text", "")).strip()
                    c_ev = [str(x) for x in c.get("supporting_evidence_ids", []) if x]
                    c_type = str(c.get("claim_type", "factual"))
                    claims.append(Claim(claim_id=c_id, text=c_text, supporting_evidence_ids=c_ev, claim_type=c_type))
                elif isinstance(c, str) and c.strip():
                    claims.append(Claim(claim_id=f"CLAIM-{i:03d}", text=c.strip()))

        # Parse techniques & CVEs
        attck_raw = data.get("attck_techniques", [])
        attck_list = [str(x).upper() for x in attck_raw if x] if isinstance(attck_raw, list) else []

        cves_raw = data.get("cves", [])
        cves_list = [str(x).upper() for x in cves_raw if x] if isinstance(cves_raw, list) else []

        # Parse limitations
        lim_raw = data.get("limitations", [])
        limitations = [str(x).strip() for x in lim_raw if x] if isinstance(lim_raw, list) else []

        # Collect all citations from claims and inline answer
        all_citations: set[str] = set()
        for c in claims:
            all_citations.update(c.supporting_evidence_ids)

        inline_cits = CITED_EVIDENCE_PATTERN.findall(answer)
        for cit in inline_cits:
            # Filter out non-evidence tags
            if any(k in cit.upper() for k in ["EVID", "EVTX", "IMG", "DOCX", "PDF", "MORD", "FLOW", "ATTACK", "CVE"]):
                all_citations.add(cit)

        return StructuredInvestigationAnswer(
            answer=answer,
            claims=claims,
            attck_techniques=attck_list,
            cves=cves_list,
            confidence=confidence,
            limitations=limitations,
            evidence_citations=sorted(all_citations),
            raw_response=raw_text,
            is_parsed_json=True,
            model_name=model_name,
            token_usage=token_usage,
        )

    @classmethod
    def _fallback_parse(
        cls,
        raw_text: str,
        model_name: str,
        token_usage: dict[str, int],
    ) -> StructuredInvestigationAnswer:
        """Heuristic fallback when model output is unstructured plain text."""
        # Find ATT&CK techniques and CVEs via regex
        attck_matches = sorted(set(m.upper() for m in ATTCK_PATTERN.findall(raw_text)))
        cve_matches = sorted(set(m.upper() for m in CVE_PATTERN.findall(raw_text)))

        # Find cited evidence IDs via regex
        inline_cits = CITED_EVIDENCE_PATTERN.findall(raw_text)
        evidence_ids = sorted(
            set(
                cit
                for cit in inline_cits
                if any(k in cit.upper() for k in ["EVID", "EVTX", "IMG", "DOCX", "PDF", "MORD", "FLOW", "ATTACK", "CVE"])
            )
        )

        # Synthesize claims by sentence splitting if sentences cite evidence
        claims: list[Claim] = []
        sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+", raw_text) if len(s.strip()) > 20]
        claim_idx = 1
        for sent in sentences:
            sent_cits = [c for c in evidence_ids if f"[{c}]" in sent or c in sent]
            if sent_cits:
                claims.append(
                    Claim(
                        claim_id=f"CLAIM-{claim_idx:03d}",
                        text=sent,
                        supporting_evidence_ids=sent_cits,
                        claim_type="inferential",
                    )
                )
                claim_idx += 1

        if not claims:
            claims.append(
                Claim(
                    claim_id="CLAIM-001",
                    text=raw_text[:300] + "..." if len(raw_text) > 300 else raw_text,
                    supporting_evidence_ids=evidence_ids,
                    claim_type="summary",
                )
            )

        limitations = [
            "Model response was unstructured plain text; claims were heuristically extracted.",
            "Phase 4 claim-level evidence verification has not been performed on these findings.",
        ]

        return StructuredInvestigationAnswer(
            answer=raw_text,
            claims=claims,
            attck_techniques=attck_matches,
            cves=cve_matches,
            confidence="preliminary",
            limitations=limitations,
            evidence_citations=evidence_ids,
            raw_response=raw_text,
            is_parsed_json=False,
            model_name=model_name,
            token_usage=token_usage,
        )
